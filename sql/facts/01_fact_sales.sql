CREATE TABLE dwh_owner.FACT_SALES (
    sales_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR2(50),
    order_item_id VARCHAR2(50) UNIQUE,
    date_key NUMBER,
    customer_key NUMBER,
    product_key NUMBER,
    store_key NUMBER,
    channel_key NUMBER,
    status_key NUMBER,
    quantity NUMBER(10),
    unit_price NUMBER(12,2),
    gross_amount NUMBER(14,2),
    discount_amount NUMBER(14,2),
    tax_amount NUMBER(14,2),
    net_amount NUMBER(14,2),
    cost_amount NUMBER(14,2),
    profit_amount NUMBER(14,2),
    batch_id VARCHAR2(50),
    loaded_at TIMESTAMP DEFAULT SYSTIMESTAMP
);